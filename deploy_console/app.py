@app.get("/api/render/env/<service_id>")
def api_render_env_get(service_id: str):
    try:
        client, _ = _render_client()
        vars_ = client.list_env_vars(service_id)
        masked = request.args.get("masked", "1") != "0"
        out = []
        sensitive = {
            "TELEGRAM_BOT_TOKEN",
            "GEMINI_API_KEY",
            "GEMINI_API_KEYS",
            "PINECONE_API_KEY",
            "RENDER_API_KEY",
        }
        for v in vars_:
            key = str(v.get("key") or "")
            val = str(v.get("value") or "")
            if masked and (key in sensitive or "TOKEN" in key or "KEY" in key or "SECRET" in key):
                val = _mask(val)
            out.append({"key": key, "value": val})
        return jsonify({"ok": True, "env": out, "masked": masked})
    except Exception as e:
        return jsonify({"ok": False, "error": str(e)}), 400


@app.post("/api/render/env/sync")
def api_render_env_sync():
    """
    Push local .env bot secrets to the selected Render service (merge, not wipe).
    Body: { service_id?, keys?: ["TELEGRAM_BOT_TOKEN", ...] }
    """
    body = request.get_json(force=True, silent=True) or {}
    try:
        client, env = _render_client()
        sid = (body.get("service_id") or env.get("RENDER_SERVICE_ID") or "").strip()
        if not sid:
            return jsonify({"ok": False, "error": "service_id required"}), 400
        default_keys = [
            "TELEGRAM_BOT_TOKEN",
            "GEMINI_API_KEY",
            "GEMINI_API_KEYS",
            "PINECONE_API_KEY",
            "ADMIN_USER_IDS",
            "INTERNAL_SERVICE_TOKEN",
            "CONSOLE_BASE_URL",
            "BOT_BASE_URL",
        ]
        keys = body.get("keys") or default_keys
        updates = {}
        for k in keys:
            v = env.get(k)
            if v:
                updates[k] = v
        if not updates:
            return jsonify({"ok": False, "error": "no local secret values to sync"}), 400
        result = client.upsert_env_vars(sid, updates)
        deploy = None
        if body.get("deploy", True):
            deploy = client.trigger_deploy(sid, clear_cache=False)
        return jsonify(
            {
                "ok": True,
                "synced_keys": list(updates.keys()),
                "env_count": len(result),
                "deploy": deploy,
            }
        )
    except Exception as e:
        return jsonify({"ok": False, "error": str(e)}), 400


