def _read_env() -> dict[str, str]:
    data: dict[str, str] = {}
    if not ENV_PATH.is_file():
        return data
    for line in ENV_PATH.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        data[k.strip()] = v.strip().strip('"').strip("'")
    return data


def _write_env(values: dict[str, str]) -> None:
    # Preserve comments from example order when possible
    order = [
        "TELEGRAM_BOT_TOKEN",
        "GEMINI_API_KEY",
        "GEMINI_API_KEYS",
        "PINECONE_API_KEY",
        "ADMIN_USER_IDS",
        "PORT",
        "RENDER_API_KEY",
        "RENDER_SERVICE_ID",
        "INTERNAL_SERVICE_TOKEN",
        "BOT_BASE_URL",
        "CONSOLE_BASE_URL",
        "CONSOLE_PASSWORD",
        "CONSOLE_USER",
    ]
    lines = [
        "# Notbook AI — generated by Deploy Console",
        f"# {time.strftime('%Y-%m-%d %H:%M:%S')}",
        "",
    ]
    seen = set()
    for k in order:
        if k in values and values[k] is not None and str(values[k]) != "":
            lines.append(f"{k}={values[k]}")
            seen.add(k)
    for k, v in values.items():
        if k in seen:
            continue
        if v is None or str(v) == "":
            continue
        lines.append(f"{k}={v}")
    ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _mask(val: str, show: int = 4) -> str:
    if not val:
        return ""
    if len(val) <= show * 2:
        return "*" * len(val)
    return val[:show] + "…" + val[-show:]


def _load_yaml() -> dict[str, Any]:
    if not CONFIG_PATH.is_file():
        return {}
    with open(CONFIG_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def _save_yaml(data: dict[str, Any]) -> None:
    # Merge into existing to preserve nested keys not in form
    existing = _load_yaml()

    def deep_merge(base: dict, patch: dict) -> dict:
        for k, v in patch.items():
            if isinstance(v, dict) and isinstance(base.get(k), dict):
                deep_merge(base[k], v)
            else:
                base[k] = v
        return base

    merged = deep_merge(existing, data)
    with open(CONFIG_PATH, "w", encoding="utf-8") as f:
        yaml.safe_dump(merged, f, default_flow_style=False, allow_unicode=True, sort_keys=False)


def _bot_pid() -> Optional[int]:
    if not PID_PATH.is_file():
        return None
    try:
        pid = int(PID_PATH.read_text(encoding="utf-8").strip())
    except ValueError:
        return None
    # Check alive
    try:
        if sys.platform == "win32":
            out = subprocess.run(
                ["tasklist", "/FI", f"PID eq {pid}"],
                capture_output=True,
                text=True,
                timeout=5,
            )
            if str(pid) in out.stdout and "python" in out.stdout.lower():
                return pid
            # also accept any process with that pid
            if str(pid) in out.stdout and "No tasks" not in out.stdout:
                return pid
        else:
            os.kill(pid, 0)
            return pid
    except Exception:
        pass
    return None


def _set_nested(d: dict, path: str, value: Any) -> None:
    parts = path.split(".")
    cur = d
    for p in parts[:-1]:
        cur = cur.setdefault(p, {})
    # coerce numbers/bools
    if isinstance(value, str):
        low = value.lower().strip()
        if low in ("true", "false"):
            value = low == "true"
        else:
            try:
                if "." in value:
                    value = float(value)
                else:
                    value = int(value)
            except ValueError:
                pass
    cur[parts[-1]] = value


