# Library upload jobs (background + realtime progress)
# ---------------------------------------------------------------------------

_upload_jobs: dict[str, dict[str, Any]] = {}
_upload_lock = threading.Lock()
_MAX_JOB_LOGS = 500


def _job_snapshot(job: dict[str, Any], *, since: int = 0) -> dict[str, Any]:
    logs = job.get("logs") or []
    return {
        "id": job["id"],
        "status": job["status"],  # queued|running|done|error
        "phase": job.get("phase") or "",
        "pct": job.get("pct") if job.get("pct") is not None else 0,
        "current": job.get("current"),
        "total": job.get("total"),
        "display_name": job.get("display_name") or "",
        "filename": job.get("filename") or "",
        "message": job.get("message") or "",
        "result": job.get("result"),
        "error": job.get("error"),
        "started_at": job.get("started_at"),
        "updated_at": job.get("updated_at"),
        "finished_at": job.get("finished_at"),
        "log_total": len(logs),
        "logs": logs[since:],
        "log_offset": since,
    }


def _append_job_log(job_id: str, event: Any) -> None:
    now = time.time()
    if isinstance(event, dict):
        msg = str(event.get("msg") or "")
        phase = str(event.get("phase") or "")
        pct = event.get("pct")
        current = event.get("current")
        total = event.get("total")
    else:
        msg = str(event)
        phase = pct = current = total = None

    ts = time.strftime("%H:%M:%S")
    line = f"[{ts}] {msg}"
    with _upload_lock:
        job = _upload_jobs.get(job_id)
        if not job:
            return
        job["logs"].append(line)
        if len(job["logs"]) > _MAX_JOB_LOGS:
            job["logs"] = job["logs"][-_MAX_JOB_LOGS:]
        job["message"] = msg
        job["updated_at"] = now
        if phase:
            job["phase"] = phase
        if pct is not None:
            try:
                job["pct"] = float(pct)
            except (TypeError, ValueError):
                pass
        if current is not None:
            job["current"] = current
        if total is not None:
            job["total"] = total


def _run_upload_job(job_id: str, dest: Path, display_name: str) -> None:
    sys.path.insert(0, str(ROOT))
    sys.path.insert(0, str(ROOT / "notbook_ai"))
    env = _read_env()
    for k, v in env.items():
        if v and k not in os.environ:
            os.environ[k] = v

    with _upload_lock:
        job = _upload_jobs.get(job_id)
        if job:
            job["status"] = "running"
            job["started_at"] = time.time()
            job["updated_at"] = time.time()
            job["phase"] = "start"
            job["pct"] = 1
            job["message"] = "Starting ingest…"

    _append_job_log(job_id, {"msg": f"Job {job_id} started", "phase": "start", "pct": 1})
    _append_job_log(
        job_id,
        {
            "msg": f"File: {dest.name} → display name: {display_name}",
            "phase": "start",
            "pct": 2,
        },
    )

    try:
        from services.ingest import ingest_service

        def progress(event) -> None:
            _append_job_log(job_id, event)

        result = ingest_service.ingest_pdf(
            str(dest), display_name, progress=progress, wipe_namespace=True
        )
        try:
            from services.gemini_service import gemini_service

            gemini_service._ns_cache = None
        except Exception:
            pass

        with _upload_lock:
            job = _upload_jobs.get(job_id)
            if job:
                job["status"] = "done"
                job["pct"] = 100
                job["phase"] = "done"
                job["result"] = result
                job["message"] = (
                    f"OK — {result.get('book')} · {result.get('chunks')} chunks"
                )
                job["finished_at"] = time.time()
                job["updated_at"] = time.time()
        _append_job_log(
            job_id,
            {
                "msg": (
                    f"Complete. ns={result.get('namespace')} "
                    f"index={result.get('index')} chunks={result.get('chunks')}"
                ),
                "phase": "done",
                "pct": 100,
                "current": result.get("chunks"),
                "total": result.get("chunks"),
            },
        )
        # Notify linked bot to refresh namespace cache
        try:
            from link_client import bot_request, link_configured

            if link_configured():
                bot_request(
                    "POST",
                    "/internal/webhook/console",
                    body={
                        "event": "library_upload",
                        "book": result.get("book"),
                        "namespace": result.get("namespace"),
                        "chunks": result.get("chunks"),
                    },
                )
                _append_job_log(
                    job_id,
                    {"msg": "Notified linked bot (library_upload)", "phase": "done", "pct": 100},
                )
        except Exception as ne:
            _append_job_log(
                job_id,
                {"msg": f"Bot notify skipped: {ne}", "phase": "done", "pct": 100},
            )
    except Exception as e:
        err = f"{type(e).__name__}: {e}"
        with _upload_lock:
            job = _upload_jobs.get(job_id)
            if job:
                job["status"] = "error"
                job["error"] = err
                job["message"] = err
                job["finished_at"] = time.time()
                job["updated_at"] = time.time()
        _append_job_log(job_id, {"msg": f"ERROR: {err}", "phase": "error"})
    finally:
        try:
            dest.unlink(missing_ok=True)
        except Exception:
            pass


